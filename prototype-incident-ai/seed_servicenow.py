"""Create realistic test incidents in a ServiceNow developer instance.

Credentials are read from environment variables or an interactive password prompt;
they are never written to disk or printed.
"""

from __future__ import annotations

import argparse
import getpass
import json
import os
import sys
from typing import Any

import httpx


SAMPLE_INCIDENTS: tuple[dict[str, Any], ...] = (
    {
        "short_description": "Checkout API pods restart during peak traffic",
        "description": "Checkout requests fail after the latest application release. Pods repeatedly restart under load.",
        "category": "software",
        "priority": "1",
        "impact": "1",
        "urgency": "1",
        "raw_logs": "java.lang.OutOfMemoryError: Java heap space\nOOMKilled exit code 137\nHTTP 503",
        "recent_changes": ["Deployed checkout-api version 4.8.0"],
    },
    {
        "short_description": "Order processing blocked by database pool exhaustion",
        "description": "Order requests hang while all PostgreSQL connections remain occupied.",
        "category": "database",
        "priority": "2",
        "impact": "2",
        "urgency": "1",
        "raw_logs": "connection pool exhausted: unable to acquire a connection\nlock wait timeout exceeded",
        "recent_changes": ["Enabled a new hourly reporting query"],
    },
    {
        "short_description": "Log ingestion stopped because node filesystem is full",
        "description": "Collectors cannot write spool files after debug logging was enabled.",
        "category": "hardware",
        "priority": "2",
        "impact": "2",
        "urgency": "2",
        "raw_logs": "write failed: No space left on device\ndisk usage 100% on /var",
        "recent_changes": ["Enabled verbose debug logging"],
    },
)


def _table_payload(sample: dict[str, Any]) -> dict[str, str]:
    logs = sample["raw_logs"]
    return {
        "short_description": sample["short_description"],
        "description": f"{sample['description']}\n\nSynthetic test incident generated by the RCA prototype.",
        "category": sample["category"],
        "impact": sample["impact"],
        "urgency": sample["urgency"],
        "work_notes": f"Synthetic source logs:\n{logs}",
    }


def _webhook_payload(sample: dict[str, Any], record: dict[str, Any]) -> dict[str, Any]:
    return {
        "sys_id": str(record["sys_id"]),
        "number": str(record.get("number", "")),
        "short_description": sample["short_description"],
        "description": sample["description"],
        "category": sample["category"],
        "priority": sample["priority"],
        "raw_logs": sample["raw_logs"],
        "recent_changes": sample["recent_changes"],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instance", default=os.getenv("SERVICENOW_INSTANCE_URL", ""), help="PDI URL")
    parser.add_argument("--username", default=os.getenv("SERVICENOW_USERNAME", "admin"))
    parser.add_argument("--count", type=int, default=3, choices=range(1, len(SAMPLE_INCIDENTS) + 1))
    parser.add_argument(
        "--forward-local",
        action="store_true",
        help="Also send each created record to the local RCA webhook (no public tunnel required)",
    )
    parser.add_argument("--local-url", default="http://127.0.0.1:8000/api/v1/servicenow/webhook")
    parser.add_argument("--dry-run", action="store_true", help="Print payloads without creating records")
    args = parser.parse_args()

    instance = args.instance.strip().rstrip("/")
    if not instance:
        parser.error("Provide --instance or set SERVICENOW_INSTANCE_URL")
    if not instance.startswith("https://"):
        parser.error("ServiceNow instance URL must start with https://")

    secret = os.getenv("SERVICENOW_SECRET", "")
    if not args.dry_run and not secret:
        secret = getpass.getpass("ServiceNow password/access token: ")
    endpoint = f"{instance}/api/now/table/incident"

    try:
        with httpx.Client(timeout=20.0) as client:
            for index, sample in enumerate(SAMPLE_INCIDENTS[: args.count], 1):
                table_payload = _table_payload(sample)
                if args.dry_run:
                    print(f"\n[{index}] POST {endpoint}\n{json.dumps(table_payload, indent=2)}")
                    continue

                response = client.post(
                    endpoint,
                    params={"sysparm_input_display_value": "false", "sysparm_exclude_reference_link": "true"},
                    headers={"Accept": "application/json", "Content-Type": "application/json"},
                    auth=(args.username, secret),
                    json=table_payload,
                )
                response.raise_for_status()
                record = response.json()["result"]
                print(f"Created {record.get('number', '(number unavailable)')} — sys_id={record['sys_id']}")

                if args.forward_local:
                    local = client.post(args.local_url, json=_webhook_payload(sample, record))
                    local.raise_for_status()
                    result = local.json()
                    confidence = result["rca"]["confidence_score"]
                    print(f"  Local RCA complete ({confidence:.1%} confidence); write-back={result['write_back']['status']}")
    except httpx.HTTPStatusError as exc:
        detail = exc.response.text[:1_000]
        print(f"Request failed with HTTP {exc.response.status_code}: {detail}", file=sys.stderr)
        return 1
    except httpx.HTTPError as exc:
        print(f"Connection failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
